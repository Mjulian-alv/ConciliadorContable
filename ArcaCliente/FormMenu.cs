using System;
using System.Windows.Forms;
using ArcaCliente.Services;

namespace ArcaCliente
{
    public partial class FormMenu : Telerik.WinControls.UI.RadForm
    {
        public FormMenu()
        {
            InitializeComponent();
            Icon = AppIcons.Arca;
        }

        protected override void OnShown(EventArgs e)
        {
            base.OnShown(e);
            ActualizarEstadoLogin();
        }

        // ?? Online ????????????????????????????????????????????????????????????????

        private void BtnOnline_Click(object sender, EventArgs e)
        {
            if (!TokenStorage.HasToken())
            {
                using var login = new FormLogin();
                if (login.ShowDialog(this) != DialogResult.OK)
                    return;
            }

            AbrirModulo(new FormComprobantes());
        }

        // ?? Offline ???????????????????????????????????????????????????????????????

        private void BtnOffline_Click(object sender, EventArgs e)
        {
            using var selector = new FormPerfilesOffline();
            if (selector.ShowDialog(this) != DialogResult.OK || selector.PerfilSeleccionado == null)
                return;

            AbrirModulo(new FormComprobantesOffline(selector.PerfilSeleccionado));
        }

        // ?? Navegación ????????????????????????????????????????????????????????????

        private void AbrirModulo(Form form)
        {
            Hide();
            form.Show();
            form.FormClosed += (s, _) =>
            {
                ActualizarEstadoLogin();
                Show();
            };
        }

        // ?? Sesión ????????????????????????????????????????????????????????????????

        private void BtnLogout_Click(object sender, EventArgs e)
        {
            if (MessageBox.Show("¿Cerrar sesión?", "Confirmar",
                    MessageBoxButtons.YesNo, MessageBoxIcon.Question) == DialogResult.Yes)
            {
                AppServices.Logout();
                ActualizarEstadoLogin();
            }
        }

        private void ActualizarEstadoLogin()
        {
            var token = AppServices.CurrentToken;
            lblUsuario.Text   = token?.Email ?? string.Empty;
            btnLogout.Visible = token != null;
        }
    }
}

